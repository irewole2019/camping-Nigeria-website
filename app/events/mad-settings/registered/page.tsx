import Image from 'next/image'
import Link from 'next/link'
import { ArrowRight, MapPin, Phone } from 'lucide-react'
import Navbar from '@/components/layout/Navbar'
import Footer from '@/components/layout/Footer'
import Section from '@/components/ui/Section'
import JsonLd from '@/components/seo/JsonLd'
import { buildPageMetadata } from '@/lib/seo'
import { buildBreadcrumbJsonLd } from '@/lib/structured-data'
import { isValidSignupCode } from '@/lib/events/mad-settings-records'
import { gatePassFields, gatePassSvg } from '@/lib/gate-pass/qr'
import { firstNameOf, getTribe, isValidTribeId, tribeBadgeAlt, type Tribe } from '@/lib/events/mad-settings-tribes'
import {
  BRING,
  EVENT_DATE_LABEL,
  EVENT_FULL_TITLE,
  EVENT_PATH,
  EVENT_PHONE_DISPLAY,
  EVENT_PHONE_TEL,
  EVENT_TIME_LABEL,
  REGISTERED_PATH,
  VENUE_LABEL,
  VENUE_MAP_URL,
  VENUE_PUBLIC_LABEL,
  getTicket,
  isValidTicketId,
} from '@/lib/events/mad-settings'

export const metadata = buildPageMetadata({
  title: `You are in — ${EVENT_FULL_TITLE} | Camping Nigeria`,
  description: 'Your MAD Settings sign-up is in. Here is your code and what to bring.',
  path: REGISTERED_PATH,
})

/**
 * Reads the code back from the URL rather than the database, so the page is
 * static and needs no lookup. The email is the durable copy; this is the
 * "it worked" moment immediately after submitting.
 *
 * Everything here is validated before it renders: an invented `?code=` that
 * does not match the MAD code shape is not echoed back, so this page cannot be
 * used to make a screenshot of a code we never issued.
 */
export default async function MadSettingsRegisteredPage({
  searchParams,
}: {
  searchParams: Promise<{
    code?: string
    name?: string
    ticket?: string
    tribe?: string
    partner?: string
    tribe2?: string
  }>
}) {
  const params = await searchParams

  const code = isValidSignupCode(params.code) ? params.code : null
  const firstName = (params.name || '').trim().split(' ')[0]
  const ticket = isValidTicketId(params.ticket) ? getTicket(params.ticket) : null
  // Like the name and ticket, read back from the URL for the "it worked"
  // moment. Editing it changes only this page: the email and the gate both
  // go by the sheet.
  const tribe = code && isValidTribeId(params.tribe) ? getTribe(params.tribe) : null
  // A couple: the second person's tribe, which the sheet never makes the same.
  const partnerTribe =
    tribe && isValidTribeId(params.tribe2) && params.tribe2 !== tribe.id ? getTribe(params.tribe2) : null
  const partnerFirst = firstNameOf((params.partner || '').slice(0, 80))
  // The Gate pass QR (R-007), drawn on the server as inline SVG. Only for a
  // code of the right shape; the name and ticket in it are a convenience for
  // whoever reads it, and the gate trusts only the code.
  const gatePass = code
    ? await gatePassSvg(gatePassFields(code, params.name || '', ticket?.label ?? ''))
    : null

  return (
    <main id="main-content">
      <JsonLd
        id="mad-settings-registered-breadcrumb-jsonld"
        data={buildBreadcrumbJsonLd([
          { name: 'Home', path: '/' },
          { name: 'Events', path: '/events' },
          { name: EVENT_FULL_TITLE, path: EVENT_PATH },
          { name: 'You are in', path: REGISTERED_PATH },
        ])}
      />

      <Navbar />

      <Section className="bg-brand-light pt-32 md:pt-40">
        <div className="mx-auto max-w-2xl">
          <div className="text-center">
            <p className="font-sans text-sm font-semibold uppercase tracking-widest text-brand-accent-readable">
              Sign-up received
            </p>
            <h1 className="mt-3 font-serif text-4xl font-bold leading-tight text-brand-dark text-balance md:text-5xl">
              {firstName ? `You are in, ${firstName}` : 'You are in'}
            </h1>
          </div>

          {code ? (
            <div className="mt-10 overflow-hidden rounded-2xl border-2 border-brand-accent bg-brand-accent-tint">
              <div className="px-6 py-8 text-center">
                <p className="font-sans text-xs font-semibold uppercase tracking-[0.2em] text-brand-accent-readable">
                  Your gate pass
                </p>
                {gatePass && (
                  <div
                    role="img"
                    aria-label={`Your gate pass, code ${code}`}
                    className="mx-auto mt-5 h-[240px] w-[240px] overflow-hidden rounded-lg bg-white [&>svg]:h-full [&>svg]:w-full"
                    // Generated by the qrcode library from our own text; it
                    // carries path data, not the guest's name as markup.
                    dangerouslySetInnerHTML={{ __html: gatePass }}
                  />
                )}
                {/* font-sans, not font-mono: the mono face in globals.css is never loaded. */}
                <p className="mt-5 font-sans text-4xl font-bold tracking-[0.15em] text-brand-dark sm:text-5xl">
                  {code}
                </p>
                <p className="mt-4 font-sans text-base font-semibold text-brand-dark">
                  Screenshot this now. Show it at the gate.
                </p>
                <p className="mt-2 font-sans text-sm text-brand-dark/65">
                  If your gate pass will not scan, your name still gets you in.
                </p>
              </div>
            </div>
          ) : (
            <p className="mt-10 rounded-lg border border-amber-200 bg-amber-50 px-4 py-3 text-center font-sans text-sm text-amber-900">
              Your sign-up went through, but we could not show your code here. Check your email — it
              is in there. If nothing arrives, email hello@campingnigeria.com.
            </p>
          )}

          {tribe && partnerTribe && (
            <div className="mt-6 rounded-2xl border-2 border-brand-accent bg-white px-4 py-7 text-center sm:px-6">
              <p className="font-sans text-xs font-semibold uppercase tracking-[0.2em] text-brand-dark/60">
                Your tribes
              </p>
              <div className="mt-4 grid grid-cols-2 gap-4">
                <TribeBadge who={firstName || 'You'} tribe={tribe} />
                <TribeBadge who={partnerFirst || 'Your partner'} tribe={partnerTribe} />
              </div>
              <p className="mt-5 font-sans text-base text-brand-dark">
                On a couple ticket, each of you belongs to a different MAD Settings tribe.
              </p>
            </div>
          )}

          {tribe && !partnerTribe && (
            <div
              className="mt-6 rounded-2xl border-2 bg-white px-6 py-7 text-center"
              style={{ borderColor: tribe.colour }}
            >
              <p className="font-sans text-xs font-semibold uppercase tracking-[0.2em] text-brand-dark/60">
                Your tribe
              </p>
              <Image
                src={tribe.image}
                alt={tribeBadgeAlt(tribe)}
                width={tribe.imageWidth}
                height={tribe.imageHeight}
                className="mx-auto mt-4 h-auto w-[220px]"
              />
              <p className="mt-4 font-sans text-base text-brand-dark">
                You are in{' '}
                <span
                  className="inline-block rounded-full px-3 py-0.5 font-bold"
                  style={{ backgroundColor: tribe.colour, color: tribe.ink }}
                >
                  {tribe.name}
                </span>
                , one of the four MAD Settings tribes.
              </p>
            </div>
          )}

          <dl className="mt-8 divide-y divide-brand-dark/10 overflow-hidden rounded-2xl border border-brand-dark/10 bg-white">
            {ticket && <Row label="Ticket" value={ticket.label} />}
            <Row label="When" value={`${EVENT_DATE_LABEL}, ${EVENT_TIME_LABEL}`} />
            {/* The venue is not public — it is shown here only alongside a
                code, so that loading this URL bare does not reveal it. The
                check is shape-only (the page is static and cannot ask the
                sheet whether a code was really issued), so the email remains
                the channel we actually rely on. */}
            {code ? (
              <Row
                label="Where"
                value={
                  <>
                    {VENUE_LABEL}
                    <br />
                    <a
                      href={VENUE_MAP_URL}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="mt-1 inline-flex items-center gap-1.5 font-semibold text-brand-accent-readable hover:underline"
                    >
                      <MapPin className="h-4 w-4" aria-hidden="true" />
                      Open in Google Maps
                    </a>
                  </>
                }
              />
            ) : (
              <Row
                label="Where"
                value={
                  <>
                    {VENUE_PUBLIC_LABEL}. The full address and map link are in your confirmation
                    email.
                  </>
                }
              />
            )}
          </dl>

          <div className="mt-10">
            <h2 className="font-serif text-xl font-bold text-brand-dark">Bring this</h2>
            <ul className="mt-4 space-y-2.5">
              {BRING.map((item) => (
                <li
                  key={item}
                  className="relative pl-5 font-sans text-[15px] leading-relaxed text-brand-dark/75"
                >
                  <span
                    className="absolute left-0 top-[0.55em] h-[7px] w-[7px] bg-brand-accent"
                    aria-hidden="true"
                  />
                  {item}
                </li>
              ))}
            </ul>
            <p className="mt-5 font-sans text-sm text-brand-dark/55">
              The full list, including what we are providing, is in your email.
            </p>
          </div>

          <div className="mt-12 flex flex-col gap-3 sm:flex-row">
            <Link
              href={EVENT_PATH}
              className="inline-flex items-center justify-center gap-2 rounded-lg bg-brand-dark px-6 py-3.5 font-sans text-sm font-semibold tracking-wide text-white transition-colors duration-200 hover:bg-brand-accent hover:text-brand-dark"
            >
              Back to MAD Settings
              <ArrowRight className="h-4 w-4" aria-hidden="true" />
            </Link>
            {/* The events line from the flyer rather than /contact — this event
                has its own enquiries number. */}
            <a
              href={EVENT_PHONE_TEL}
              className="inline-flex items-center justify-center gap-2 rounded-lg border border-brand-dark/25 px-6 py-3.5 font-sans text-sm font-semibold tracking-wide text-brand-dark transition-colors duration-200 hover:border-brand-dark hover:bg-brand-dark hover:text-white"
            >
              <Phone className="h-4 w-4" aria-hidden="true" />
              {EVENT_PHONE_DISPLAY}
            </a>
          </div>
        </div>
      </Section>

      <Footer />
    </main>
  )
}

function TribeBadge({ who, tribe }: { who: string; tribe: Tribe }) {
  return (
    <div className="flex flex-col items-center">
      <p className="font-sans text-sm font-bold text-brand-dark">{who}</p>
      <Image
        src={tribe.image}
        alt={tribeBadgeAlt(tribe)}
        width={tribe.imageWidth}
        height={tribe.imageHeight}
        className="mt-2 h-auto w-full max-w-[180px]"
      />
      <span
        className="mt-3 inline-block rounded-full px-3 py-0.5 font-sans text-sm font-bold"
        style={{ backgroundColor: tribe.colour, color: tribe.ink }}
      >
        {tribe.name}
      </span>
    </div>
  )
}

function Row({ label, value }: { label: string; value: React.ReactNode }) {
  return (
    <div className="grid grid-cols-[88px_1fr] gap-4 px-5 py-4 sm:grid-cols-[110px_1fr] sm:px-6">
      <dt className="font-sans text-[10px] font-bold uppercase tracking-[0.16em] text-brand-dark/45">
        {label}
      </dt>
      <dd className="font-sans text-sm leading-relaxed text-brand-dark/85">{value}</dd>
    </div>
  )
}
